import { readFile, writeFile } from 'node:fs/promises';
import { productContent } from '../src/data/productContent';

// The full editorial copy belongs to the lazy product screen. Extract only
// descriptions for the shared SEO code so other pages do not download all guides.
const descriptions = Object.fromEntries(Object.entries(productContent).map(([id, text]) => [id, {
    TR: text!.TR.description,
    EN: text!.EN.description,
}]));
const file = new URL('../src/data/productMetadata.ts', import.meta.url);
const source = `// Generated by npm run content:generate. Edit productContent/*.ts instead.\nimport type { TranslatedString } from './products/types';\n\nexport const productMetadata: Partial<Record<number, TranslatedString>> = ${JSON.stringify(descriptions, null, 4)};\n`;
const current = await readFile(file, 'utf8').catch(() => '');
if (current !== source) await writeFile(file, source);
console.log(`Product metadata: ${Object.keys(descriptions).length} bilingual descriptions ready.`);
