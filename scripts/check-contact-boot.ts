import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';

const dom = new JSDOM('<a id="wa" href="https://wa.me/905431707277?text=private-message" target="_blank">WhatsApp</a><a id="phone" href="tel:+905431707277" target="_blank">Call</a><a id="other" href="/products">Products</a>', { url: 'https://parsogutma.com/products/14?email=visitor@example.com' });
const win = dom.window as Window & typeof globalThis;
Object.defineProperty(globalThis, 'window', { configurable: true, value: win });
Object.defineProperty(globalThis, 'Element', { configurable: true, value: win.Element });
const calls: unknown[][] = [];
(win as any).gtag = (...args: unknown[]) => { calls.push(args); };
const { initializeAnalytics } = await import('../src/lib/analytics');
const { installContactTracking } = await import('../src/lib/contactTracking');
const { trackContactClick } = await import('../src/lib/googleAds');
initializeAnalytics();
initializeAnalytics();
assert.equal(calls.filter(call => call[0] === 'config').length, 1, 'Early/application entries configured GA4 twice');
installContactTracking(win.document);
installContactTracking(win.document);
// Prevent jsdom's simulated navigation after our listener has processed it.
win.document.addEventListener('click', event => event.preventDefault());
const conversions = () => calls.filter(call => call[1] === 'conversion').length;
const event = () => new win.MouseEvent('click', { bubbles: true, cancelable: true });
const wa = win.document.getElementById('wa') as HTMLAnchorElement;
wa.dispatchEvent(event());
assert.equal(conversions(), 1, 'Static contact link was not measured before hydration');
const native = event();
trackContactClick({ nativeEvent: native, currentTarget: wa, defaultPrevented: false, preventDefault: () => native.preventDefault(), ctrlKey: false, metaKey: false, shiftKey: false, altKey: false, button: 0 }, 'whatsapp');
wa.dispatchEvent(native);
assert.equal(conversions(), 2, 'One React/native click produced duplicate Ads conversions');
assert.equal(calls.filter(call => call[1] === 'whatsapp_click').length, 2, 'One click produced duplicate GA4 events');
const cancelled = event();
cancelled.preventDefault();
wa.dispatchEvent(cancelled);
assert.equal(conversions(), 2, 'Cancelled/dragged click was measured');
win.document.getElementById('other')!.dispatchEvent(event());
assert.equal(conversions(), 2, 'Ordinary navigation was measured as a contact');
win.document.getElementById('phone')!.dispatchEvent(event());
assert.equal(conversions(), 3);
assert.equal((calls.filter(call => call[1] === 'conversion').at(-1)![2] as any).send_to, 'AW-300255429/6ADOCOjoheIYEMWRlo8B');
assert.equal(calls.filter(call => call[1] === 'phone_click').length, 1);
assert(!JSON.stringify(calls).includes('private-message') && !JSON.stringify(calls).includes('visitor@example.com'), 'Contact tracking sent message/query data');
dom.window.close();
console.log('Early contact checks passed: static links measured, shared GA4 configured once, React/delegated clicks deduplicated, cancelled clicks and private text excluded.');
