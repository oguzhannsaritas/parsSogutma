import { mkdir, rm, writeFile } from 'node:fs/promises';
import { products } from '../src/data/products';
import { productContent } from '../src/data/productContent';
import { isCanonicalProduct } from '../src/data/catalog';
import type { ProductSummary } from '../src/data/products/types';

const summaries: ProductSummary[] = products.map(({ specs, ...product }) => {
    const { optionalAccessory: _accessories, technicalSpecification: _technical, ...summarySpecs } = specs;
    return { ...product, specs: summarySpecs };
});
await writeFile('src/data/productSummaries.ts', `// Generated by scripts/generate-product-data.ts.\nimport type { ProductSummary } from './products/types';\nexport const products: ProductSummary[] = [\n${summaries.map(product => JSON.stringify(product)).join(',\n')}\n];\n`);
const directory = 'public/product-data/v1';
await rm(directory, { recursive: true, force: true });
await mkdir(directory, { recursive: true });
for (const product of products.filter(isCanonicalProduct)) {
    const content = productContent[product.id];
    if (!content?.TR || !content.EN) throw new Error(`Missing product copy: ${product.id}`);
    await writeFile(`${directory}/${product.id}.json`, JSON.stringify({ version: 1, product, content }));
}
console.log(`Product data: ${summaries.length} summaries and ${products.filter(isCanonicalProduct).length} complete model files.`);
