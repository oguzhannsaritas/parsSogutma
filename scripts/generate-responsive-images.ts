import { mkdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import { products } from '../src/data/products';
import { isCanonicalProduct } from '../src/data/catalog';
import { getProductMainImage } from '../src/seo/config';

const sources = [...new Set([
    ...products.filter(isCanonicalProduct).map(getProductMainImage),
    ...['buzdolabi2', 'masa', 'marketx', 'sogukHava2', 'sogutma', 'sogutmareyon', 'unluMamullx', 'sustanion'].map(name => `/images/home/${name}.webp`),
])].sort();
const manifest: Record<string, { width: number; height: number; widths: number[] }> = {};
let next = 0;
let generated = 0;
async function worker() {
    while (next < sources.length) {
        const source = sources[next++];
        const file = path.join('public', source);
        const info = await stat(file);
        const metadata = await sharp(file).metadata();
        if (!metadata.width || !metadata.height) throw new Error(`Missing image dimensions: ${source}`);
        const maximum = Math.min(metadata.width, 1920);
        const widths = [...new Set([... [160, 320, 480, 640, 960, 1280].filter(width => width < maximum), maximum])];
        manifest[source] = { width: metadata.width, height: metadata.height, widths };
        for (const width of widths) {
            const target = path.join('public/images/responsive', String(width), source.slice('/images/'.length));
            const previous = await stat(target).catch((error: NodeJS.ErrnoException) => {
                if (error.code !== 'ENOENT') throw error;
                return undefined;
            });
            if (previous && previous.mtimeMs >= info.mtimeMs) continue;
            await mkdir(path.dirname(target), { recursive: true });
            await sharp(file).resize({ width, withoutEnlargement: true }).webp({ quality: 82 }).toFile(target);
            generated++;
        }
    }
}
await Promise.all(Array.from({ length: 4 }, worker));
const ordered = Object.fromEntries(sources.map(source => [source, manifest[source]]));
await writeFile('src/data/responsiveImageManifest.ts', `// Generated by scripts/generate-responsive-images.ts.\nexport const responsiveImageManifest: Record<string, { width: number; height: number; widths: number[] }> = {\n${Object.entries(ordered).map(([source, image]) => `${JSON.stringify(source)}: ${JSON.stringify(image)}`).join(',\n')}\n};\n`);
console.log(`Responsive images: ${sources.length} covers, ${generated} variants generated.`);
